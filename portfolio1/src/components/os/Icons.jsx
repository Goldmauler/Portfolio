export default function PixelIcon({ name, scale = 2 }) {
  const rows = BITMAPS[name] || BITMAPS.doc;
  const w = rows[0].length;
  const h = rows.length;
  const rects = [];
  rows.forEach((row, y) => {
    let x = 0;
    while (x < w) {
      if (row[x] !== '#') {
        x++;
        continue;
      }
      let end = x;
      while (end < w && row[end] === '#') end++;
      rects.push(<rect key={`${x}-${y}`} x={x} y={y} width={end - x} height={1} />);
      x = end;
    }
  });
  return (
    <svg
      className="pixel-icon"
      width={w * scale}
      height={h * scale}
      viewBox={`0 0 ${w} ${h}`}
      shapeRendering="crispEdges"
      fill="currentColor"
      aria-hidden="true"
    >
      {rects}
    </svg>
  );
}
